unimplemented_sorted = sorted(unimplemented, key=lambda x: (x['prefecture'], x['pop_order']))

# 3グループに分割
group_size = len(unimplemented_sorted) // 3
remainder = len(unimplemented_sorted) % 3

groups = []
start_idx = 0
for i in range(3):
    size = group_size + (1 if i < remainder else 0)
    groups.append(unimplemented_sorted[start_idx:start_idx + size])
    start_idx += size

